/** The channel a URL lives on, if any: hyperadapted.substack.com → Substack. */
export function socialFor(href: string): Social | undefined {
    const host = new URL(href).hostname;
    return socials.find((s) => s.hosts.some((h) => host === h || host.endsWith(`.${h}`)));
}
